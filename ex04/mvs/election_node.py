"""
Code generated by Claude Opus 5.5

leader election node: follower / candidate / leader with terms, votes and heartbeats
(raft style election only, no log replication), messages are json over udp

usage: python3 election_node.py <name> <name=host:port> ... [--timeout MIN MAX] [--start-at EPOCH] [--run S] [--fresh]
e.g.   python3 election_node.py A A=172.31.0.10:6000 B=172.31.0.11:6000 C=172.31.0.12:6000
"""
import argparse
import json
import os
import random
import signal
import socket
import time
from types import SimpleNamespace

HEARTBEAT_INTERVAL = 0.05  #50ms
REPORT_INTERVAL = 1.0  #print received heartbeats once per second instead of 20 lines

parser = argparse.ArgumentParser()
parser.add_argument("name")
parser.add_argument("nodes", nargs="+", help="name=host:port of every node, including this one")
parser.add_argument("--timeout", nargs=2, type=float, default=[150, 300], metavar=("MIN", "MAX"),
                    help="election timeout range in ms, MIN = MAX turns off the randomization")
parser.add_argument("--start-at", type=float, help="unix time to start the timers, so all nodes start together")
parser.add_argument("--run", type=float, help="stop after this many seconds")
parser.add_argument("--fresh", action="store_true", help="delete the saved term / vote first")
args = parser.parse_args()

name = args.name
nodes = {}
for entry in args.nodes:
    node, addr = entry.split("=")
    host, port = addr.split(":")
    nodes[node] = (socket.gethostbyname(host), int(port))
peers = [n for n in nodes if n != name]
majority = len(nodes) // 2 + 1
state_file = f"state_{name}.json"

#current_term and voted_for are persistent (state file), the rest is volatile
st = SimpleNamespace(term=0, voted_for=None, role="follower", leader=None, votes=set(),
                     election_deadline=0.0, election_started=0.0, last_heartbeat=None,
                     next_heartbeat=0.0, received={}, acks={})


def log(msg):
    now = time.time()
    print(f"[{name} {time.strftime('%H:%M:%S', time.localtime(now))}.{int(now % 1 * 1000):03d}] {msg}", flush=True)


def save_state():
    #write + fsync + rename, a crash in the middle leaves the old file, never a half written one
    tmp = state_file + ".tmp"
    with open(tmp, "w") as f:
        json.dump({"current_term": st.term, "voted_for": st.voted_for}, f)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, state_file)


def load_state():
    if args.fresh and os.path.exists(state_file):
        os.remove(state_file)
    if not os.path.exists(state_file):
        return False
    with open(state_file) as f:
        saved = json.load(f)
    st.term, st.voted_for = saved["current_term"], saved["voted_for"]
    return True


def send(to, msg_type, **fields):
    msg = {"type": msg_type, "term": st.term, "from": name, **fields}
    try:
        sock.sendto(json.dumps(msg).encode(), nodes[to])
    except OSError:
        pass  #e.g. blocked by the firewall, same as a lost udp message


def broadcast(msg_type):
    for peer in peers:
        send(peer, msg_type)


def reset_election_timer():
    st.election_deadline = time.monotonic() + random.uniform(*args.timeout) / 1000


def step_down(term, reason):
    #any message with a higher term: adopt it, forget the old vote, become follower
    old_role = st.role
    change = f", {old_role} -> follower" if old_role != "follower" else ""
    log(f"term {st.term} -> {term} ({reason}){change}")
    st.term, st.voted_for, st.role, st.leader = term, None, "follower", None
    save_state()
    if old_role != "follower":
        reset_election_timer()


def start_election():
    now = time.monotonic()
    if st.role == "candidate":
        reason = f"no majority in term {st.term}"
    elif st.leader:
        reason = f"no heartbeat from {st.leader} for {(now - st.last_heartbeat) * 1000:.0f} ms"
    else:
        reason = "no leader"
    st.role, st.term, st.voted_for, st.leader = "candidate", st.term + 1, name, None
    save_state()
    st.votes = {name}
    st.election_started = now
    reset_election_timer()
    log(f"election timeout, {reason} -> candidate, term {st.term}")
    broadcast("vote_req")


def become_leader():
    st.role, st.leader = "leader", name
    st.next_heartbeat = time.monotonic()  #first heartbeat right away
    took = (time.monotonic() - st.election_started) * 1000
    log(f"elected leader, term {st.term}, votes {sorted(st.votes)} ({took:.1f} ms after becoming candidate)")


def on_vote_req(msg):
    candidate = msg["from"]
    granted = msg["term"] == st.term and st.voted_for in (None, candidate)
    if granted:
        st.voted_for = candidate
        save_state()  #persist before answering, so a restart can't vote twice in this term
        reset_election_timer()
        log(f"vote for {candidate} in term {st.term}")
    else:
        log(f"reject vote for {candidate} in term {msg['term']} (term {st.term}, voted for {st.voted_for})")
    send(candidate, "vote_resp", granted=granted)


def on_vote_resp(msg):
    if st.role != "candidate" or msg["term"] != st.term:
        return  #answer to an older election
    if not msg["granted"]:
        log(f"{msg['from']} rejected the vote, term {st.term}")
        return
    st.votes.add(msg["from"])
    log(f"vote from {msg['from']} ({len(st.votes)}/{len(nodes)}, need {majority})")
    if len(st.votes) >= majority:
        become_leader()


def on_heartbeat(msg):
    sender = msg["from"]
    if msg["term"] < st.term:
        #stale leader, the answer carries our term so it steps down
        log(f"reject heartbeat from {sender} (term {msg['term']} < {st.term})")
        send(sender, "heartbeat_resp", success=False)
        return
    if st.role == "candidate":
        log(f"heartbeat from {sender} in term {st.term}, candidate -> follower")
        st.role = "follower"
    if st.leader != sender:
        log(f"following {sender}, term {st.term}")
    st.leader = sender
    st.last_heartbeat = time.monotonic()
    st.received[sender] = st.received.get(sender, 0) + 1
    reset_election_timer()
    send(sender, "heartbeat_resp", success=True)


def on_heartbeat_resp(msg):
    if st.role == "leader" and msg["success"]:
        st.acks[msg["from"]] = st.acks.get(msg["from"], 0) + 1


def handle(msg):
    if msg["term"] > st.term:
        step_down(msg["term"], f"{msg['type']} from {msg['from']}")
    handlers = {"vote_req": on_vote_req, "vote_resp": on_vote_resp,
                "heartbeat": on_heartbeat, "heartbeat_resp": on_heartbeat_resp}
    handlers[msg["type"]](msg)


def report():
    if st.role == "leader":
        acks = ", ".join(f"{n} {st.acks.get(n, 0)}" for n in peers)
        log(f"leader, term {st.term}, heartbeat acks in the last 1s: {acks}")
    elif st.received:
        got = ", ".join(f"{n} {c}" for n, c in st.received.items())
        log(f"{st.role}, term {st.term}, heartbeats in the last 1s: {got}")
    st.received, st.acks = {}, {}


signal.signal(signal.SIGTERM, signal.default_int_handler)  #kill (not -9) stops it like ctrl+c

sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
sock.bind(("0.0.0.0", nodes[name][1]))

if load_state():
    log(f"restored term {st.term}, voted for {st.voted_for} from {state_file}")
if args.start_at:
    time.sleep(max(args.start_at - time.time(), 0))
log(f"start as follower, term {st.term}, cluster {list(nodes)}, majority {majority}, "
    f"timeout {args.timeout[0]:.0f}-{args.timeout[1]:.0f} ms")
started = time.monotonic()
reset_election_timer()
next_report = started + REPORT_INTERVAL

try:
    while not args.run or time.monotonic() - started < args.run:
        now = time.monotonic()
        if st.role == "leader" and now >= st.next_heartbeat:
            broadcast("heartbeat")
            #fixed 50ms grid, now + 50ms would drift by the loop delay every time
            st.next_heartbeat = max(st.next_heartbeat + HEARTBEAT_INTERVAL, now)
        if st.role != "leader" and now >= st.election_deadline:
            start_election()
        if now >= next_report:
            report()
            next_report = max(next_report + REPORT_INTERVAL, now)  #no burst of reports after a stall

        #single thread: wait for a message until the next timer is due
        due = st.next_heartbeat if st.role == "leader" else st.election_deadline
        sock.settimeout(max(min(due, next_report) - time.monotonic(), 0.0005))
        try:
            data, _ = sock.recvfrom(4096)
        except socket.timeout:
            continue
        handle(json.loads(data))
except KeyboardInterrupt:
    pass
log(f"stop as {st.role}, term {st.term}")
