"""
Code generated by Claude Opus 5.5
Replicated counter (task 1.1 and 1.2), merge with max

Every node keeps its own counter and increments it locally. The value is sent
to the peer over UDP after every increment, and every SYNC_INTERVAL seconds
once the increments stopped. On receive:
    counter = max(local_counter, received_counter)

usage:
    python3 replicated_max.py <name> <listen port> <peer host:port> [increments] [recv delay]

    python3 replicated_max.py A 5000 <ip of B>:5001 10
    python3 replicated_max.py B 5001 <ip of A>:5000 7

recv delay (seconds, default 0) starts the receive thread later. Messages that
arrive before that wait in the socket buffer, so both nodes can increment before
they merge anything (concurrent increments, task 1.2):

    python3 replicated_max.py A 5000 <ip of B>:5001 1 5
    python3 replicated_max.py B 5001 <ip of A>:5000 1 5
"""
import random
import socket
import sys
import threading
import time

SYNC_INTERVAL = 0.5
SYNC_ROUNDS = 10  #sync rounds after the increments stopped

name = sys.argv[1]
port = int(sys.argv[2])
peer_host, peer_port = sys.argv[3].split(":")
peer = (peer_host, int(peer_port))
increments = int(sys.argv[4]) if len(sys.argv) > 4 else 10
recv_delay = float(sys.argv[5]) if len(sys.argv) > 5 else 0

counter = 0
lock = threading.Lock()  #receive thread and main thread both write counter
sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
sock.bind(("0.0.0.0", port))


def log(msg):
    print(f"[{name} {time.strftime('%H:%M:%S')}] {msg}", flush=True)


def receive():
    global counter
    last = None
    while True:
        data, _ = sock.recvfrom(64)
        received = int(data.decode())
        with lock:
            old = counter
            counter = max(counter, received)
            new = counter
        if new != old:
            log(f"recv {received}, counter {old} -> {new}")
        elif received != last:
            log(f"recv {received}, counter stays {new}")
        last = received


def sync():
    with lock:
        value = counter
    sock.sendto(str(value).encode(), peer)


receiver = threading.Timer(recv_delay, receive)
receiver.daemon = True
receiver.start()
log(f"listening on {port}, peer {peer[0]}:{peer[1]}, {increments} increments")
time.sleep(3)  #time to start the other node

for _ in range(increments):
    with lock:
        counter += 1
        value = counter
    log(f"inc, counter = {value}")
    sync()
    time.sleep(random.uniform(0.1, 0.5))

log(f"increments stopped ({increments} local), only syncing now")
for _ in range(SYNC_ROUNDS):
    sync()
    time.sleep(SYNC_INTERVAL)

with lock:
    log(f"final counter = {counter}")
