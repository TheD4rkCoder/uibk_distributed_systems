"""
Code generated by Claude Opus 5.5
Single-copy counter (task 2), one counter in redis shared by both nodes

The nodes don't talk to each other, they only send commands to redis.
Increment modes:
    unsafe  GET, +1 locally, SET (read-modify-write, not safe)
    incr    INCR, atomic in redis
    lock    take a lock (SET lock NX PX), then GET/SET, then release it
    watch   WATCH/MULTI/EXEC, the transaction fails if the counter changed
            after WATCH, then it is retried

hold (seconds, default 0) is a sleep between GET and SET, it makes an update
take longer, so the other node tries to update while it is in progress.

Both nodes wait for each other (key "ready") before they start, so the
increments really run at the same time. Reset first:
    redis6-cli set counter 0
    redis6-cli set ready 0

usage:
    python3 single_copy.py <name> <redis host> <mode> [increments] [hold]

    python3 single_copy.py A <ip of store> incr 1000
    python3 single_copy.py B <ip of store> incr 1000
"""
import sys
import time

import redis

LOCK_TIMEOUT_MS = 10000  #lock expires if the holder dies

name = sys.argv[1]
host = sys.argv[2]
mode = sys.argv[3]
increments = int(sys.argv[4]) if len(sys.argv) > 4 else 1000
hold = float(sys.argv[5]) if len(sys.argv) > 5 else 0

r = redis.Redis(host=host, port=6379)


def log(msg):
    print(f"[{name} {time.strftime('%H:%M:%S')}] {msg}", flush=True)


def incr_unsafe():
    value = int(r.get("counter"))
    time.sleep(hold)
    r.set("counter", value + 1)
    return value + 1, 0


def incr_atomic():
    return r.incr("counter"), 0


def incr_lock():
    #returns the time spent waiting for the lock
    start = time.perf_counter()
    while not r.set("lock", name, nx=True, px=LOCK_TIMEOUT_MS):
        time.sleep(0.001)
    waited = time.perf_counter() - start
    value = int(r.get("counter"))
    time.sleep(hold)
    r.set("counter", value + 1)
    r.delete("lock")
    return value + 1, waited


def incr_watch():
    #returns how often the transaction failed
    retries = 0
    with r.pipeline() as pipe:
        while True:
            try:
                pipe.watch("counter")
                value = int(pipe.get("counter"))
                time.sleep(hold)
                pipe.multi()
                pipe.set("counter", value + 1)
                pipe.execute()
                return value + 1, retries
            except redis.WatchError:
                retries += 1


MODES = {"unsafe": incr_unsafe, "incr": incr_atomic, "lock": incr_lock, "watch": incr_watch}
increment = MODES[mode]

log(f"redis {host}, mode {mode}, {increments} increments, hold {hold}s")
r.incr("ready")
while int(r.get("ready")) < 2:  #wait for the other node
    time.sleep(0.001)
log("start")

extra = 0
slowest = 0
start = time.perf_counter()
for i in range(increments):
    t = time.perf_counter()
    value, x = increment()
    extra += x
    slowest = max(slowest, time.perf_counter() - t)
    if hold > 0:
        log(f"inc {i + 1}, counter = {value}, took {time.perf_counter() - t:.3f}s"
            + (f", waited {x:.3f}s for the lock" if mode == "lock" else "")
            + (f", {x} retries" if mode == "watch" else ""))
total = time.perf_counter() - start

log(f"done, {increments} increments in {total:.3f}s ({total / increments * 1000:.3f} ms per increment)")
log(f"slowest increment {slowest * 1000:.3f} ms")
if mode == "lock":
    log(f"waited {extra:.3f}s for the lock in total")
if mode == "watch":
    log(f"{extra} failed transactions (retried)")
log(f"counter now = {int(r.get('counter'))}")
