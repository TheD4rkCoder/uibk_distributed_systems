import json
import signal
import sys
import threading
import time

import zenoh

PUBLISH_INTERVAL = 2

name = sys.argv[1]
connect = sys.argv[2] if len(sys.argv) > 2 else None

peers = set()
lock = threading.Lock()  #liveliness callback and main thread both use peers


def log(msg):
    print(f"[{name} {time.strftime('%H:%M:%S')}] {msg}", flush=True)


def open_session():
    conf = zenoh.Config()
    conf.insert_json5("mode", '"peer"')
    if connect:  #no multicast in the vpc, so connect to the router instead
        conf.insert_json5("connect/endpoints", json.dumps([connect]))
    return zenoh.open(conf)


def on_liveliness(sample):
    other = str(sample.key_expr).split("/")[-1]
    if other == name:
        return
    with lock:
        if sample.kind == zenoh.SampleKind.PUT:
            peers.add(other)
            log(f"join {other}")
        else:
            peers.discard(other)
            log(f"leave {other}")


def on_hello(sample):
    sender = str(sample.key_expr).split("/")[-1]
    if sender != name:  #the session also gets its own puts
        log(f"recv from {sender}: {sample.payload.to_string()}")


signal.signal(signal.SIGTERM, signal.default_int_handler)  #kill stops it like ctrl+c

session = open_session()
watcher = session.liveliness().declare_subscriber("mesh/nodes/*", on_liveliness, history=True)
token = session.liveliness().declare_token(f"mesh/nodes/{name}")
sub = session.declare_subscriber("mesh/hello/*", on_hello)
pub = session.declare_publisher(f"mesh/hello/{name}")
log(f"online, zid {session.info.zid()}")

try:
    i = 0
    while True:
        time.sleep(PUBLISH_INTERVAL)
        i += 1
        pub.put(f"Hello from Node {name} #{i}")
        with lock:
            known = sorted(peers)
        log(f"sent hello #{i}, peers {known}")
except KeyboardInterrupt:
    pass
finally:
    token.undeclare()
    session.close()
