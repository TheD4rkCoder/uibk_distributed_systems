import json
import re
import sys

from kazoo.client import KazooClient

zk = KazooClient(hosts=sys.argv[1])
zk.start(timeout=15)
auctions = sys.argv[2].split(",")
lines = [l for f in sys.argv[3:] for l in open(f)]

acked = {m.group(1) for l in lines for m in [re.search(r"accepted, id (\S+)", l)] if m}
unknown = {m.group(1) for l in lines for m in [re.search(r"outcome unknown, id (\S+)", l)] if m}

print("| Auction | Accepted bids | Increasing | Winner = highest | All bids before close | Close results | Not acked |")
print("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
committed = set()
ok_all = True
for a in auctions:
    data, stat = zk.get(f"/auctions/{a}")
    state = json.loads(data)
    bids = []
    for child in sorted(zk.get_children(f"/auctions/{a}/bids")):
        d, s = zk.get(f"/auctions/{a}/bids/{child}")
        bids.append((json.loads(d), s.czxid))
    amounts = [b["amount"] for b, _ in bids]
    ids = [b["id"] for b, _ in bids]
    committed |= set(ids)
    increasing = all(x < y for x, y in zip(amounts, amounts[1:]))
    last = bids[-1][0] if bids else None
    winner_ok = state["status"] == "closed" and state["winner"] == last == state["highest"]
    #the closed state is never written again, so its mzxid is the zxid of the close
    before_close = all(czxid < stat.mzxid for _, czxid in bids)
    results = {l.split(": ", 1)[1].split(" (v")[0].replace("already ", "") for l in lines if f"close {a}: " in l and "closed by" in l}
    not_acked = [i for i in ids if i not in acked]
    ok = increasing and winner_ok and before_close and len(results) == 1
    ok_all &= ok
    w = state["winner"]
    winner = f"{w['bidder']} {w['amount']}" if w else "no winner"
    print(f"| {a} | {len(bids)} | {'yes' if increasing else 'NO'} | {'yes' if winner_ok else 'NO'} ({winner}) "
          f"| {'yes' if before_close else 'NO'} | {len(results)} | {len(not_acked)} |")

lost = acked - committed
print(f"\nacked bids: {len(acked)}, lost: {len(lost)}")
print(f"outcome unknown: {len(unknown)}, of these committed: {len(unknown & committed)}")
print("all invariants hold" if ok_all and not lost else "INVARIANT VIOLATED")
zk.stop()
